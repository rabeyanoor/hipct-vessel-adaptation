# kaggle_kernels/colab/make_colab_notebook.py
"""
Writes a Colab notebook that runs a job list on a Colab TPU (or GPU) runtime
with the same code, data and job runner as the Kaggle kernels:
the inputs are downloaded into /kaggle/input with the Kaggle API, and
/kaggle/working is a folder on Google Drive, so a training run resumes from its
state.pth when the notebook is run again in a later session.

Usage:
    python kaggle_kernels/colab/make_colab_notebook.py kaggle_kernels/jobs/colab_tpu.json \
        kaggle_kernels/colab/colab_tpu.ipynb
"""

import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))

SETUP = r'''import os, subprocess, glob
os.environ["KAGGLE_CONFIG_DIR"] = "/root/.kaggle"
def sh(c):
    print("$", c, flush=True)
    subprocess.run(c, shell=True, check=True)
sh("pip install -q kaggle")
I = "/kaggle/input"
sh(f"mkdir -p {I}/datasets/rabeya100x/hip-vesseladapt-code {I}/datasets/rabeya100x/sam-med3d-weights {I}/rois {I}/blood-vessel-segmentation")
sh(f"kaggle datasets download rabeya100x/hip-vesseladapt-code -p {I}/datasets/rabeya100x/hip-vesseladapt-code --unzip -q")
sh(f"kaggle datasets download rabeya100x/sam-med3d-weights -p {I}/datasets/rabeya100x/sam-med3d-weights --unzip -q")
sh(f"kaggle kernels output rabeya100x/hip-vesseladapt-rois -p {I}/rois -q")
# only the training kidneys (images of kidney_3_dense live in kidney_3_sparse)
if not os.path.isdir(f"{I}/blood-vessel-segmentation/train/kidney_1_dense"):
    sh(f"kaggle competitions download -c blood-vessel-segmentation -p /content -q")
    sh(f"cd {I}/blood-vessel-segmentation && unzip -q -o /content/blood-vessel-segmentation.zip "
       "'train/kidney_1_dense/*' 'train/kidney_2/*' 'train/kidney_3_sparse/*' 'train/kidney_3_dense/*' && rm /content/blood-vessel-segmentation.zip")
sh("df -h /content | tail -1; free -g | head -2; nproc")'''

TPU = r'''# PyTorch/XLA for the TPU runtime (same versions as the Kaggle TPU image)
import subprocess
subprocess.run("pip install -q torch==2.8.0 'torch_xla[tpu]==2.8.0'", shell=True, check=True)
subprocess.run("python -c \"import torch_xla, torch; print(torch.__version__, torch_xla.device())\"", shell=True, check=True)'''

RUN = r'''import os
os.makedirs(DRIVE_OUT, exist_ok=True)
if not os.path.islink("/kaggle/working"):
    os.makedirs("/kaggle", exist_ok=True)
    os.symlink(DRIVE_OUT, "/kaggle/working")
os.environ["PJRT_DEVICE"] = "TPU"   # remove this line on a GPU runtime
!python /content/kernel.py 2>&1 | tee -a /kaggle/working/colab_session.log'''


def md(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text.splitlines(True)}


def code(text):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": text.splitlines(True)}


def main():
    jobs, out = sys.argv[1], sys.argv[2]
    with tempfile.TemporaryDirectory() as d:
        k = os.path.join(d, "kernel.py")
        subprocess.run([sys.executable, os.path.join(HERE, "..", "launch_jobs.py"), jobs, "--slug", "colab",
                        "--tpu", "--keep-state", "--write", k], check=True)
        kernel = open(k).read()
    name = os.path.splitext(os.path.basename(jobs))[0]
    cells = [
        md(f"# HiP-VesselAdapt on Colab: `{name}`\n\n"
           "Runtime → Change runtime type → **TPU**. Then run the cells in order. "
           "Cells 1 and 2 need you (Google Drive access; your `kaggle.json` from kaggle.com → Settings → API). "
           "Training state is saved on Drive after every epoch, so running the notebook again later resumes the run.\n"
           f"\nJob list: `kaggle_kernels/jobs/{name}.json`; generated by `kaggle_kernels/colab/make_colab_notebook.py`."),
        code("# 1. Google Drive (outputs and resume state)\n"
             "from google.colab import drive\n"
             "drive.mount('/content/drive')\n"
             f"DRIVE_OUT = '/content/drive/MyDrive/hip-vesseladapt/{name}'"),
        code("# 2. Kaggle API key: choose your kaggle.json\n"
             "import os\n"
             "if not os.path.exists('/root/.kaggle/kaggle.json'):\n"
             "    from google.colab import files\n"
             "    up = files.upload()\n"
             "    os.makedirs('/root/.kaggle', exist_ok=True)\n"
             "    open('/root/.kaggle/kaggle.json', 'wb').write(up['kaggle.json'])\n"
             "    os.chmod('/root/.kaggle/kaggle.json', 0o600)"),
        code("# 3. Inputs (code, SAM-Med3D weights, ROIs, training kidneys)\n" + SETUP),
        code("# 4. PyTorch/XLA (TPU runtime only)\n" + TPU),
        code("# 5. Job runner (kaggle_kernels/kaggle_jobs_kernel.py with the job list filled in)\n"
             "%%writefile /content/kernel.py\n" + kernel.replace("%%writefile", "")),
        code("# 6. Run (log of each job: DRIVE_OUT/out/<job>.log)\n" + RUN),
        code("# progress\n!tail -n 5 /kaggle/working/out/*.log"),
    ]
    # %%writefile must be the first line of its cell
    cells[5] = code("%%writefile /content/kernel.py\n# 5. Job runner (kaggle_kernels/kaggle_jobs_kernel.py with the job list filled in)\n" + kernel)
    nb = {"cells": cells, "metadata": {"accelerator": "TPU", "colab": {"provenance": []},
                                       "kernelspec": {"name": "python3", "display_name": "Python 3"}},
          "nbformat": 4, "nbformat_minor": 0}
    json.dump(nb, open(out, "w"), indent=1)
    print(f"[✓] {out}")


if __name__ == "__main__":
    main()
