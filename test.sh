  -----------------------------------------|-----------|-------|-------|--------|------------|------------|------------------------
  Zero-shot SAM-Med3D (no training)       | 0%        | 0.088 | 0.052 | 0.076  | 48.1       | 25.2       | 79/100
  PhysicsAwareAdapter (10 epochs)         | 7.65%     | 0.157 | 0.094 | 0.139  | 36.2       | inf*       | 71/100
  Plain LoRA, r=4 (10 epochs)             | 7.75%     | 0.067 | 0.038 | 0.057  | 45.7       | 24.8       | 76/100
  Spacing-Conditioned LoRA, r=4 (10 ep)   | 8.88%     | 0.206 | 0.131 | 0.261  | 23.4       | inf*       | 80/100

THIS IS THE PROJECT'S CORE RESULT: Spacing-Conditioned LoRA (the proposed
method) beats every other model on every metric, including its most direct
ablation (Plain LoRA -- identical architecture and training protocol, the
ONLY difference is spacing modulation of the LoRA branch). Trainable overhead
is modest (8.88% vs 7.65-7.75%), not a capacity-driven advantage.

HONEST, NOT-HOPED-FOR FINDING: Plain LoRA (10 epochs) underperforms even the
untrained zero-shot baseline, and is well below both adapter-based methods.
Reported exactly as measured, no cherry-picking. Plausible explanations, none
yet confirmed: LoRA modifies attention INSIDE the frozen encoder while the
adapter modifies the encoder's OUTPUT directly before the decoder (a shorter
optimization path for the same ~170-220 gradient steps); all three trained
runs used identical loss weights/learning rate (tuned originally against
PhysicsAwareAdapter), never re-tuned per architecture -- a real confound, but
Spacing-Conditioned LoRA still won despite it; 10 epochs may simply be too
few for Plain LoRA specifically -- yet Spacing-Conditioned LoRA (same LoRA
mechanism + spacing modulation) converged to a much lower training loss under
the identical protocol (1.56 vs Plain LoRA's 2.05), suggesting spacing
conditioning itself, not just "more LoRA training," made the difference.
Needs more investigation (per-architecture LR sweep, multiple seeds) before
treating this ranking as final.

* ASSD=inf for PhysicsAwareAdapter AND Spacing-Conditioned LoRA, reported
honestly not hidden: a MONAI warning ("the prediction of class 0 is all 0")
indicates at least one evaluated patch had a completely empty prediction.
Plain LoRA's ASSD on the identical evaluation protocol did NOT hit this
(24.8, finite) -- worth investigating before trusting ASSD from either
winning model.

RESOLVED 2026-09-15 (diagnose_assd_inf.py): an earlier investigation had
tested exactly this "completely empty prediction" hypothesis on 15 patches
and confirmed 0 of them, leaving the cause open. A fresh, larger diagnostic
run (125 non-empty patches for PhysicsAwareAdapter, 92 for Spacing-
Conditioned LoRA, calling MONAI's SurfaceDistanceMetric per-patch instead of
only on the batch average) DID reproduce one genuine ASSD=inf case for
Spacing-Conditioned LoRA, and it was in fact a completely-empty prediction
(pred_sum=0) -- on a patch with a vanishingly small annotated target (22
voxels, 0.01% of the 64^3 patch, kidney_3_dense). PhysicsAwareAdapter's
checkpoint produced 0/125 such cases in this same run. CONCLUSION: the
empty-prediction hypothesis was right all along -- it's a rare,
patch-draw-dependent event (roughly 1% of non-empty-target patches in this
draw) tied to the model completely missing tiny/sparse vessel fragments at
only 10 epochs, not a deterministic property of either checkpoint. The
earlier "0 confirmed of 15" result most likely just didn't happen to draw
one of these rare small-target patches -- 15 samples was too few to
reliably catch a ~1%-rate event. A second, more specific hypothesis (a
FULLY SATURATED prediction, the opposite extreme, also has no detectable
surface and would also produce inf) was tested alongside and found 0
occurrences of either kind for PhysicsAwareAdapter and 0 fully-saturated
cases for Spacing-Conditioned LoRA -- ruled out as a contributing cause here.

A real bug was found and fixed while building this evaluation: the external
clDice library's soft_cldice.forward(y_true, y_pred) returns 1-clDice (a
LOSS, same convention as soft_dice() in the same file), not the raw score.
The first run of this evaluation reported clDice=0.978 alongside Dice=0.025
-- inconsistent almost by construction. That 0.978 was the loss value,
misread as a score. Fixed to `1.0 - cldice_fn(targets, binary_pred).item()`;
corrected scores now sit in the same range as Dice, as they should. The
training-loss usage in losses/combined_loss.py was already correct (it
legitimately wants a loss to minimize) and was unaffected.

Model size:
  PhysicsAwareAdapter:      Total 100,622,065 / Trainable 7,697,137 (7.65%)
  Plain LoRA:               Total 100,730,416 / Trainable 7,805,488 (7.75%)
  Spacing-Conditioned LoRA: Total 101,985,328 / Trainable 9,060,400 (8.88%)
  (Spacing FiLM networks add ~1.25M params over Plain LoRA; trainable
