2. MODEL / ARCHITECTURE
================================================================

Backbone: SAM-Med3D (https://github.com/openmedlab/SAM-Med3D), official
pretrained checkpoint (external/SAM-Med3D/ckpt/sam_med3d.pth, 1.2GB,
downloaded from the repo's Google Drive link). Loaded with model_type=
"vit_b_ori" (768-dim encoder, 128^3 pretraining resolution) -- the correct
architecture variant for this specific checkpoint, confirmed by loading with
0 missing and 0 unexpected keys (registry's default "vit_b" is a different,
384-dim/256^3 variant and would silently mismatch).

  Total parameters (HiPVesselAdaptModel): 100,622,065
  Trainable parameters (adapter + mask_decoder + collapse_head): 7,697,137 (7.65%)

Modules:
  - models/physics_adapter.py: PhysicsAwareAdapter -- spacing-conditioned
    bottleneck adapter (spacing -> Linear/GELU/Linear -> elementwise
    modulation -> low-rank down/up projection residual).
  - models/collapse_head.py: CollapseDetectionHead -- Conv3d/BatchNorm/ReLU/
    Conv3d/Sigmoid multi-task head. Present, runs, UNTRAINED/UNVALIDATED --
    no supervision signal built for it yet.
  - models/lora.py + models/plain_lora_model.py: PlainLoRAModel -- frozen
    backbone, LoRA (r=4, alpha=1.0) injected into all 24 attention qkv/proj
    layers (12 transformer blocks x 2 layers, confirmed by count), NO
    spacing conditioning. Trained and evaluated, see section 3.2.
  - models/spacing_lora.py + models/spacing_lora_model.py:
    SpacingConditionedLoRAModel -- this project's main proposed method. Same
    LoRA injection points as PlainLoRAModel, but each LoRA branch's output is
    additionally FiLM-modulated (gamma, beta) by a small per-layer spacing
    encoder fed real physical voxel spacing. Spacing is threaded through by
    setting a plain (non-parameter) `current_spacing` attribute on each
    injected layer immediately before the encoder forward call, rather than
    editing SAM-Med3D's unmodified Attention.forward(). A design flaw was
    caught and fixed BEFORE training: the FiLM network's hidden size
    originally scaled with attention out_features, adding ~31M trainable
    params for the qkv layers alone (31.79% of the model) -- fixed to a
    fixed small hidden size (16), landing at 8.88% trainable, a fair
    comparison to Plain LoRA's 7.75%. Trained and evaluated, see section 3.2.
  - SAM-Med3D's mask_decoder is a PROMPTABLE head. Called with no prompt, it
    was verified (empirically, via direct probability inspection) to
    collapse to predicting exactly 1.0 everywhere after training. Fixed
    with an auto-prompt: two corner points spanning the whole reference
    volume, standing in for a whole-volume box (SAM-Med3D's own box-embedding
    code has a hardcoded 2D-only reshape that crashes for this 3D port).

Loss (losses/combined_loss.py, HiPVesselLoss):
  total = dice_loss + alpha*cldice_loss + beta*anisotropic_penalty + gamma*weighted_BCE
  alpha=0.5, beta=0.05, gamma=1.0 (defaults)
  - dice_loss: standard soft Dice on probabilities.
  - cldice_loss: external/clDice's soft_cldice (topology-preserving).
  - anisotropic_penalty: mean squared spatial gradient of the prediction,
    scaled by real per-axis voxel spacing.
  - weighted_BCE: BCEWithLogitsLoss on raw logits, pos_weight computed
    per-batch from the real foreground ratio (clamped to max 50). Added
    specifically because plain Dice+clDice let training collapse to
    predicting 1.0 everywhere (verified: that degenerate solution scores
    ~0.96 total loss vs ~0.02 for a near-perfect prediction under
    dice+clDice+aniso ALONE -- yet training still converged there, because
    sigmoid gradients vanish at saturation before optimization can find the
    low-loss basin. BCE-on-logits does not have this vanishing-gradient
    problem.)

