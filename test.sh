3.3 RESOLUTION-OOD TEST (most important experiment) -- REVERSES section 3.2's ranking
--------------------------------------------------------------
All three trained models evaluated on kidney_1_voi (5.2um), held out from ALL
training (a genuine ~10x unseen resolution shift, training was exclusively
~50um). 40 patches sampled, 34-35 excluded as empty-target.

  Model                     | In-dist Dice (50um) | OOD Dice (5.2um) | OOD IoU | OOD clDice | OOD HD95 | OOD ASSD
  ---------------------------|----------------------|-------------------|---------|------------|----------|----------
  PhysicsAwareAdapter        | 0.157                | 0.064             | 0.035   | 0.059      | 53.1     | 25.3
  Plain LoRA                 | 0.067                | 0.067 (best)      | 0.036   | 0.210      | 50.7     | 25.9
  Spacing-Conditioned LoRA   | 0.206 (best in-dist) | 0.002 (worst)     | 0.001   | 0.008      | 41.6     | 18.7

THIS REVERSES THE IN-DISTRIBUTION RANKING and is reported exactly as
measured, no cherry-picking. Spacing-Conditioned LoRA -- the clear
in-distribution winner -- collapses to near-zero Dice (0.002) on the unseen
resolution, worse than both other models on Dice/IoU/clDice.

HYPOTHESIS 1 TESTED AND REFUTED: guessed the spacing-FiLM network would
extrapolate badly ~10x out-of-range (trained on effectively one spacing
value, ~50um) and produce large/erratic gamma/beta at 5.2um. Checked
directly: spacing_film(spacing) at 50um gives gamma in [0.70, 1.54] (mean
1.05); at 5.2um gamma is in [0.97, 1.06] (mean 1.01) -- SMALLER and TAMER
than in-distribution, the opposite of the hypothesis. The FiLM network is
NOT confirmed as the cause.

HYPOTHESIS 2 (field-of-view domain shift), PARTIALLY SUPPORTED: a 64^3 patch
at 5.2um covers a ~10x smaller physical field of view (~333um vs ~3200um
across) than any training patch. Direct evidence: target foreground fraction
is ~20x higher on average at 5.2um (mean 0.67%, up to 6.7%, n=10) than at
50um (mean 0.032%, up to 0.67%, n=10) -- consistent with the same real
vessel occupying proportionally more of a much smaller physical window.
z-score normalization checked and ruled out as the issue (both resolutions
normalize to mean~=0, std~=0.90-0.98). However, the frozen image_encoder's
raw output statistics are nearly identical between resolutions (50um:
mean=0.0013 std=0.218; 5.2um: mean=0.0014 std=0.221) -- ruling out a gross
activation blowup in the backbone itself. The remaining open question is
whether the encoder/LoRA weights (trained only on 50um patches) recognize
the WRONG semantic content at 5.2um despite similar aggregate statistics --
not yet confirmed, would need per-channel/spatial analysis.

CONCLUSION FOR THE PAPER: the proposed method is NOT yet shown to generalize
across resolutions -- current evidence suggests it generalizes WORSE than
Plain LoRA on real out-of-distribution data. This is more scientifically
important than the in-distribution win in section 3.2 and must be reported
as the headline finding, not buried under it. Root cause remains open.

